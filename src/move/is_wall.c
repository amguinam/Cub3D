#include "game.h"

int	is_wall(t_game *g, int x, int y)
{
	if (x < 0 || x >= g->map.width || y < 0 || y >= g->map.height
		|| g->map.cell[y][x] == CELL_WALL)
		return (1);
	return (0);
}
